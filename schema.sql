DROP VIEW  IF EXISTS v_bill_itemized, v_bill_by_service, v_bill_simple CASCADE;
DROP TABLE IF EXISTS bill, customs_declaration, hazmat_detail, delivery,
                     tracking_event, package, payment_method, service_rate,
                     service, recipient, customer, location CASCADE;


-- LOCATION: anything a package can be "at": trucks, planes, warehouses
-- (carrier hubs), and customer/recipient street addresses.

CREATE TABLE location (
    location_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_type   VARCHAR(16) NOT NULL
        CHECK (location_type IN ('TRUCK','PLANE','WAREHOUSE','ADDRESS')),
    name            VARCHAR(80),            -- vehicle id or facility name
    carrier         VARCHAR(10)
        CHECK (carrier IN ('UPS','USPS')),  -- owner of truck/plane/warehouse
    street_number   VARCHAR(10),            -- only for ADDRESS rows
    street_name     VARCHAR(60),
    city            VARCHAR(60),
    state_province  VARCHAR(30),
    postal_code     VARCHAR(12),
    country         CHAR(2) NOT NULL DEFAULT 'US',
    -- vehicles and warehouses must be named; addresses must have a street
    CONSTRAINT chk_location_fields CHECK (
        (location_type IN ('TRUCK','PLANE','WAREHOUSE') AND name IS NOT NULL AND carrier IS NOT NULL)
     OR (location_type = 'ADDRESS' AND street_number IS NOT NULL
                                   AND street_name IS NOT NULL AND city IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_location_vehicle_name
    ON location (name) WHERE location_type IN ('TRUCK','PLANE','WAREHOUSE');
CREATE INDEX idx_location_street ON location (street_name, city, state_province);

-- ---------------------------------------------------------------------
-- CUSTOMER (shippers) and RECIPIENT (people who receive packages)
-- ---------------------------------------------------------------------
CREATE TABLE customer (
    customer_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    phone               VARCHAR(20),
    customer_type       VARCHAR(12) NOT NULL
        CHECK (customer_type IN ('CONTRACT','CREDIT_CARD','PREPAID')),
    address_location_id INT NOT NULL REFERENCES location(location_id)
);
CREATE INDEX idx_customer_address ON customer (address_location_id);

CREATE TABLE recipient (
    recipient_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    phone               VARCHAR(20),
    address_location_id INT NOT NULL REFERENCES location(location_id)
);

-- SERVICE and its price rules (price = base_price + per_lb * weight)
CREATE TABLE service (
    service_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier      VARCHAR(10) NOT NULL CHECK (carrier IN ('UPS','USPS')),
    service_name VARCHAR(60) NOT NULL,
    speed        VARCHAR(10) NOT NULL CHECK (speed IN ('OVERNIGHT','TWO_DAY','STANDARD')),
    typical_days SMALLINT    NOT NULL CHECK (typical_days > 0),
    UNIQUE (carrier, service_name)
);

CREATE TABLE service_rate (
    service_id   INT           NOT NULL REFERENCES service(service_id),
    package_type VARCHAR(10)   NOT NULL
        CHECK (package_type IN ('ENVELOPE','SMALL_BOX','LARGE_BOX')),
    base_price   NUMERIC(8,2)  NOT NULL CHECK (base_price >= 0),
    per_lb       NUMERIC(6,2)  NOT NULL CHECK (per_lb >= 0),
    PRIMARY KEY (service_id, package_type)
);

-- PAYMENT METHOD (only the last 4 digits of a card are ever stored)

CREATE TABLE payment_method (
    payment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INT NOT NULL REFERENCES customer(customer_id),
    method_type    VARCHAR(12) NOT NULL
        CHECK (method_type IN ('ACCOUNT','CREDIT_CARD','PREPAID')),
    account_number VARCHAR(20),   -- contract account or prepaid label code
    card_brand     VARCHAR(12),
    card_last4     CHAR(4),
    CONSTRAINT chk_payment_fields CHECK (
        (method_type = 'CREDIT_CARD' AND card_brand IS NOT NULL AND card_last4 IS NOT NULL)
     OR (method_type IN ('ACCOUNT','PREPAID') AND account_number IS NOT NULL)
    )
);
CREATE INDEX idx_payment_customer ON payment_method (customer_id);

-- PACKAGE
-- charge is stored on purpose: it is a snapshot of the price at ship
-- time (rates change later), so it is not a normalization violation.

CREATE TABLE package (
    package_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(30)   NOT NULL UNIQUE,
    sender_id       INT           NOT NULL REFERENCES customer(customer_id),
    recipient_id    INT           NOT NULL REFERENCES recipient(recipient_id),
    service_id      INT           NOT NULL REFERENCES service(service_id),
    payment_id      INT           NOT NULL REFERENCES payment_method(payment_id),
    package_type    VARCHAR(10)   NOT NULL
        CHECK (package_type IN ('ENVELOPE','SMALL_BOX','LARGE_BOX')),
    weight_lb       NUMERIC(6,2)  NOT NULL CHECK (weight_lb > 0),
    declared_value  NUMERIC(10,2) NOT NULL CHECK (declared_value >= 0),
    ship_date       DATE          NOT NULL,
    charge          NUMERIC(8,2)  NOT NULL CHECK (charge >= 0),
    FOREIGN KEY (service_id, package_type) REFERENCES service_rate(service_id, package_type),
    CONSTRAINT chk_weight_by_type CHECK (
        (package_type = 'ENVELOPE'  AND weight_lb <= 1)
     OR (package_type = 'SMALL_BOX' AND weight_lb <= 10)
     OR (package_type = 'LARGE_BOX' AND weight_lb <= 50))
);
CREATE INDEX idx_package_sender    ON package (sender_id, ship_date);
CREATE INDEX idx_package_ship_date ON package (ship_date);
CREATE INDEX idx_package_recipient ON package (recipient_id);
CREATE INDEX idx_package_service   ON package (service_id);


-- TRACKING EVENT: time-stamped history, one row per scan/move

CREATE TABLE tracking_event (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id  INT         NOT NULL REFERENCES package(package_id),
    location_id INT         NOT NULL REFERENCES location(location_id),
    event_type  VARCHAR(20) NOT NULL
        CHECK (event_type IN ('PICKED_UP','SCANNED','LOADED','ARRIVED',
                              'OUT_FOR_DELIVERY','DELIVERED')),
    event_time  TIMESTAMP   NOT NULL,
    UNIQUE (package_id, event_time, event_type)
);
CREATE INDEX idx_event_package_time ON tracking_event (package_id, event_time);
CREATE INDEX idx_event_location     ON tracking_event (location_id, event_time);


-- DELIVERY (exists only once a package has been delivered)
-- vehicle_location_id is NULL for international hand-offs.

CREATE TABLE delivery (
    delivery_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id          INT NOT NULL UNIQUE REFERENCES package(package_id),
    vehicle_location_id INT REFERENCES location(location_id),
    promised_at         TIMESTAMP NOT NULL,
    delivered_at        TIMESTAMP NOT NULL,
    signed_by           VARCHAR(100)
);
CREATE INDEX idx_delivery_vehicle ON delivery (vehicle_location_id, delivered_at);
CREATE INDEX idx_delivery_late    ON delivery (delivered_at, promised_at);


-- SPECIAL HANDLING

CREATE TABLE hazmat_detail (
    package_id           INT PRIMARY KEY REFERENCES package(package_id),
    un_number            VARCHAR(8)   NOT NULL,   -- e.g. UN3481
    hazard_class         VARCHAR(6)   NOT NULL,   -- e.g. 9, 3, 2.1
    proper_shipping_name VARCHAR(100) NOT NULL
);

CREATE TABLE customs_declaration (
    package_id          INT PRIMARY KEY REFERENCES package(package_id),
    contents            VARCHAR(120) NOT NULL,
    declared_value      NUMERIC(10,2) NOT NULL CHECK (declared_value >= 0),
    origin_country      CHAR(2) NOT NULL DEFAULT 'US',
    destination_country CHAR(2) NOT NULL,
    CHECK (origin_country <> destination_country)
);


-- BILL: one row per customer per month (filled by queries.sql, Q7)

CREATE TABLE bill (
    bill_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INT NOT NULL REFERENCES customer(customer_id),
    bill_month   DATE NOT NULL CHECK (bill_month = date_trunc('month', bill_month)::date),
    total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    issued_on    DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (customer_id, bill_month)
);
